def _normalize(text: str) -> str:
    return re.sub(r"\s+", "", text or "")


# 句首噪声前缀：这些词本身没有检索价值，还会污染截断兜底
_PREFIX_NOISE = (
    "网传", "网上流传", "网上传闻", "据说", "听说", "传闻", "有消息称",
    "近日有消息称", "近日", "有网友称", "网友爆料", "有人说", "传言",
)
# 兜底切分用的分隔符
_SEG_SPLIT = re.compile(r"[，。,.;；：:！!？?、\s\"“”‘’（）()【】\[\]/|]")


def _strip_prefix(norm: str) -> str:
    """去掉句首的"网传/据说"类噪声，避免污染截断兜底。"""
    for _ in range(3):
        for p in sorted(_PREFIX_NOISE, key=len, reverse=True):
            if norm.startswith(p) and len(norm) > len(p) + 2:
                norm = norm[len(p):]
                break
        else:
            break
    return norm


def _fallback_terms(norm: str) -> list[str]:
    """词典未命中时的兜底：按标点切分，取像词的实词片段。"""
    norm = _strip_prefix(norm)
    cands: list[str] = []
    for part in _SEG_SPLIT.split(norm):
        part = part.strip()
        if len(part) < 2:
            continue
        # 片段过长时按虚词再切一刀
        buf = ""
        for ch in part:
            if ch in _BOUNDARY_CHARS:
                if len(buf) >= 2:
                    cands.append(buf)
                buf = ""
            else:
                buf += ch
        if len(buf) >= 2:
            cands.append(buf)
        if len(part) <= 8 and part not in cands:
            cands.append(part)
    out: list[str] = []
    for c in sorted(set(cands), key=len, reverse=True):
        if c in _STOPWORDS or len(c) > 8:
            continue
        if c[0] in _BOUNDARY_CHARS or c[-1] in _BOUNDARY_CHARS:
            continue
        out.append(c)
        if len(out) >= 3:
            break
    return out
def _is_valid_gram(gram: str) -> bool:
    """判断 n-gram 是否像一个完整中文词。"""
    if len(gram) < 2 or not re.fullmatch(r"[\u4e00-\u9fa5]+", gram):
        return False
    if gram in _STOPWORDS:
        return False
    if gram[0] in _BOUNDARY_CHARS or gram[-1] in _BOUNDARY_CHARS:
        return False
    if any(c in _INNER_STOP for c in gram):
        return False
    return True
def extract_keywords(text: str, limit: int = 5) -> list[str]:
    """提取核心关键词。
    优先级：实体词典 > 数量表达 > 白名单二字词 > 整句兜底。
    """
    norm = _strip_prefix(_normalize(text))
    if not norm:
        return []
    hits: list[str] = []
    # 1) 实体词典（最长优先，避免短词吃掉长词）
    for ent in sorted(_ENTITY_LEXICON, key=len, reverse=True):
        if ent in norm and ent not in hits:
            if any(ent != h and ent in h for h in hits):
                continue
            hits.append(ent)
            if len(hits) >= limit:
                break
    # 2) 数量表达
    for m in _NUM_PATTERN.findall(norm):
        m = m.strip()
        if m and m not in hits and len(hits) < limit:
            hits.append(m)
    # 3) 白名单二字词兜底
    if len(hits) < 2:
        for i in range(len(norm) - 1):
            gram = norm[i:i + 2]
            if gram in _COMMON_WORDS and gram not in hits:
                hits.append(gram)
            if len(hits) >= limit:
                break
    # 4) 兜底：先按标点/虚词切出实词片段，再退化为整句
    if len(hits) < 2:
        for term in _fallback_terms(norm):
            if term not in hits:
                hits.append(term)
            if len(hits) >= 2:
                break
    if not hits:
        hits = [_strip_prefix(norm)[:12]]
    return hits[:limit]
def build_queries(keywords: list[str], text: str, max_queries: int = 6) -> list[str]:
    """构造检索式，兼顾精确与召回。"""
    queries: list[str] = []
    def _add(q: str) -> None:
        q = q.strip()
        if q and q not in queries and len(queries) < max_queries:
            queries.append(q)
    if text and len(text) <= 30:
        _add(text)
    if len(keywords) >= 2:
        _add(f"{keywords[0]} {keywords[1]}")
    for kw in keywords[:3]:
        _add(kw)
    if keywords:
        _add(f"{keywords[0]} 是真的吗")
        _add(f"{keywords[0]} 辟谣 真相")
    return queries[:max_queries]